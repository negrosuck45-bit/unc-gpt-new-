test('uses Lunar-owned server OAuth routes and never sends OAuth secrets to browser code', () => {
  const start = source('app/api/auth/[provider]/start/route.ts')
  const callback = source('app/api/auth/[provider]/callback/route.ts')

  assert.match(start, /accounts\.google\.com\/o\/oauth2\/v2\/auth/)
  assert.match(start, /discord\.com\/api\/oauth2\/authorize/)
  assert.match(start, /github\.com\/login\/oauth\/authorize/)
  assert.match(start, /beginLunarOAuth/)
  assert.match(callback, /validateLunarOAuthState/)
  assert.match(callback, /client_secret: config\.clientSecret/)
  assert.match(callback, /oauth2\.googleapis\.com\/token/)
  assert.match(callback, /discord\.com\/api\/oauth2\/token/)
  assert.match(callback, /github\.com\/login\/oauth\/access_token/)
  assert.match(callback, /email_verified !== true/)
  assert.match(callback, /profile\.verified !== true/)
  assert.match(callback, /lunarAuthSuccess/)
  assert.doesNotMatch(start, /NEXT_PUBLIC.*SECRET|client_secret/)
})


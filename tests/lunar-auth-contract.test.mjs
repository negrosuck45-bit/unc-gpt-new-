test('preserves existing user-owned data through a fail-closed legacy account bridge', () => {
  const session = source('lib/auth.ts')
  const bridge = source('lib/legacy-account-bridge.ts')
  const migration = source('SUPABASE_LUNAR_AUTH_IDENTITIES.sql')

  const callback = source('app/api/auth/[provider]/callback/route.ts')
  const lunarAuth = source('lib/lunar-auth.ts')
  assert.match(callback, /resolveLunarAccountScope/)
  assert.match(callback, /const accountScope = await resolveLunarAccountScope\(user\)/)
  assert.match(callback, /lunarAuthSuccess\(request, user, accountScope\)/)
  assert.match(session, /sub: session\.accountScope/)
  assert.match(lunarAuth, /account_scope: accountScope/)
  assert.match(lunarAuth, /isValidAccountScope\(payload\.account_scope, payload\.sub\)/)
  assert.match(bridge, /CLERK_SECRET_KEY/)
  assert.match(bridge, /provider_user_id/)
  assert.match(bridge, /email_address/)
  assert.match(bridge, /primary_email_address_id/)
  assert.match(bridge, /verification\?\.status === "verified"/)
  assert.match(bridge, /scopes\.length === 1/)
  assert.match(bridge, /ignoreDuplicates: true/)
  assert.match(bridge, /return user\.sub/)
  assert.doesNotMatch(bridge, /NEXT_PUBLIC.*CLERK_SECRET_KEY/)
  assert.match(migration, /create table if not exists public\.lunar_auth_identities/)
  assert.match(migration, /enable row level security/)
  assert.match(migration, /revoke all on table public\.lunar_auth_identities from anon, authenticated/)
  assert.match(migration, /lunar_auth_identities_no_client_access/)
})

